function getPage2ImageFolder(item) {
  const hobbyRoot = Array.isArray(item.hobby) ? item.hobby[0] : item.hobby;
  const hobbyParts = Array.isArray(item.hobby) ? item.hobby : [item.hobby];

  if (hobbyRoot === "園芸") return "gardening";
  if (hobbyRoot === "料理") return "cooking";
  if (
    hobbyParts.includes("食材") &&
    (hobbyRoot === "採取" || hobbyRoot === "販売" || hobbyRoot === "食材")
  ) {
    return "store-ingredient";
  }
  return "";
}

function getPage2WagonType(item) {
  const hobbyParts = Array.isArray(item.hobby) ? item.hobby : [item.hobby];
  if (!hobbyParts.includes("料理")) return "";

  // 不気味な系は背景画像なし
  if (typeof item.name === "string" && item.name.startsWith("不気味な")) {
    return "none";
  }

  // 温泉卵（通常/スノーシーズン）はどちらも背景画像なし
  if (item.name === "温泉卵") return "none";

  if (item.season === "snowseason") return "penguin-stove";
  if (item.season === "dreamlightfes") return "popcorn-wagon";

  // 通常・その他イベント・現時点で未分類のイベント料理はコンロ
  return "stove";
}

function applyPage2ItemAssets(item) {
  const folder = getPage2ImageFolder(item);
  if (folder) {
    item.img = `img/${folder}/${item.name}.png`;
  }

  const wagonType = getPage2WagonType(item);
  if (wagonType) {
    item.wagon = wagonType;
  }
}

page2Creatures.forEach((item) => {
  applyPage2ItemAssets(item);
});

// 園芸の time（hour）を「○時間○分」に変換する表示用ヘルパー
function formatHourToJpTime(hourValue) {
  const totalMinutes = Math.round((Number(hourValue) || 0) * 60);
  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;

  if (hours === 0) return `${minutes}分`;
  if (minutes === 0) return `${hours}時間`;
  return `${hours}時間${minutes}分`;
}

